const P = ({ d, f = 'none', w = 1.6, s = INK, o }: { d: string; f?: string; w?: number; s?: string; o?: number }) => <path d={d} fill={f} stroke={s} strokeWidth={w} strokeLinejoin="round" strokeLinecap="round" opacity={o} />;
