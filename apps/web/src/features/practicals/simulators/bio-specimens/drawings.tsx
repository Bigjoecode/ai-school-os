const LEAF = '#7fb069';

/** Insect body facing left: head at x, thorax, abdomen to x2. */
function insectLegs(cx: number, cy: number, spread = 1, colour = INK) {
  return (
    <g>
      {[-1, 0, 1].map((k) => (
        <g key={k}>
          <P d={`M${cx + k * 14} ${cy - 6} l${-8 + k * 6} ${-22 * spread} l${-10 + k * 4} ${-10 * spread}`} s={colour} w={1.4} />
          <P d={`M${cx + k * 14} ${cy + 6} l${-8 + k * 6} ${22 * spread} l${-10 + k * 4} ${10 * spread}`} s={colour} w={1.4} />
        </g>
      ))}
    </g>
  );
}

