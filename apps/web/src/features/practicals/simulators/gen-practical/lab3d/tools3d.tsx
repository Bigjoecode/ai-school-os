const GEO = { b: new BoxGeometry(1, 1, 1), c: new CylinderGeometry(1, 1, 1, 14), s: new SphereGeometry(1, 14, 10) };

export function Tool3d({ shape, glow }: { shape: GenToolShape; glow?: boolean }) {
  const parts = useMemo(() => SHAPES[shape] ?? SHAPES.generic, [shape]);
  return (
    <group>
      {parts.map(([g, s, p, c, tilt], i) => (
        <mesh key={i} geometry={GEO[g]} material={colourMaterial(c)} position={p} scale={s} rotation={tilt ? [tilt, 0, 0] : undefined} />
      ))}
      {glow && <GlowRing r={0.13} />}
    </group>
  );
}
