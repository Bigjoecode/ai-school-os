import type { CuratedQuestion, GameWord, MatchPack, TrueFalseFact } from '../games-content';
import type { GameLevel } from '../games';

/**
 * EduGames content for junior secondary: JSS 1–3 (ages 11–14), written for
 * BECE preparation. Topics follow the NECO BECE syllabi (topic names taken
 * from apps/api/prisma/syllabi/bece where they fit) and the NERDC Basic
 * Education curriculum. Nigerian names, places and naira; British spelling.
 *
 * Quiz questions list the right answer first (`a`) and three wrong ones (`w`);
 * the server mixes the options before a student sees them.
 * `years` = the JSS classes an item suits (null = the whole of JSS 1–3).
 */

const LEVEL: GameLevel = 'JUNIOR';

type QRow = [q: string, a: string, w: [string, string, string], topic: string, years: number[] | null, explain?: string];
type FRow = [statement: string, answer: boolean, explain: string, topic: string, years: number[] | null];
type WRow = [word: string, meaning: string, sentence: string, years: number[] | null];

const qs = (code: string, subject: string, rows: QRow[]): CuratedQuestion[] =>
  rows.map(([q, a, w, topic, years, explain], i) => ({
    id: `js-q-${code}-${i + 1}`,
    level: LEVEL,
    subject,
    topic,
    q,
    a,
    w,
    ...(explain ? { explain } : {}),
    ...(years ? { years } : {}),
  }));

const fs = (code: string, subject: string, rows: FRow[]): TrueFalseFact[] =>
  rows.map(([statement, answer, explain, topic, years], i) => ({
    id: `js-tf-${code}-${i + 1}`,
    level: LEVEL,
    subject,
    topic,
    statement,
    answer,
    explain,
    ...(years ? { years } : {}),
  }));

const ws = (subject: string | undefined, rows: WRow[]): GameWord[] =>
  rows.map(([word, meaning, sentence, years]) => ({
    word,
    level: LEVEL,
    meaning,
    sentence,
    ...(subject ? { subject } : {}),
    ...(years ? { years } : {}),
  }));

