import type { CuratedQuestion, GameWord, MatchPack, TrueFalseFact } from '../games-content';
import type { GameLevel } from '../games';

/**
 * EduGames content for senior secondary (SSS 1–3, ages 14–18): WAEC/NECO SSCE
 * and JAMB UTME style quick recall. Topics follow the WAEC/JAMB syllabus topic
 * names. Every calculation was worked out and every fact checked; ids are
 * stable (prefix `ss-`), so never renumber a block — add new rows at the end.
 */

const L: GameLevel = 'SENIOR';

type QRow = [string, string, [string, string, string], string | null, string?];
type FRow = [string, boolean, string, string | null];
type WRow = [string, string, string];

/** A block of quiz questions; `code` must be unique in this file and rows only ever appended. */
const qs = (subject: string, code: string, years: number[] | null, rows: QRow[]): CuratedQuestion[] =>
  rows.map(([q, a, w, topic, explain], i) => ({
    id: `ss-q-${code}-${i + 1}`,
    level: L,
    subject,
    topic,
    q,
    a,
    w,
    ...(explain ? { explain } : {}),
    ...(years ? { years } : {}),
  }));

/** A block of true-or-false facts; `code` must be unique in this file. */
const tfs = (subject: string, code: string, years: number[] | null, rows: FRow[]): TrueFalseFact[] =>
  rows.map(([statement, answer, explain, topic], i) => ({
    id: `ss-f-${code}-${i + 1}`,
    level: L,
    subject,
    topic,
    statement,
    answer,
    explain,
    ...(years ? { years } : {}),
  }));

const wds = (subject: string | undefined, years: number[] | null, rows: WRow[]): GameWord[] =>
  rows.map(([word, meaning, sentence]) => ({
    word,
    level: L,
    meaning,
    sentence,
    ...(subject ? { subject } : {}),
    ...(years ? { years } : {}),
  }));

